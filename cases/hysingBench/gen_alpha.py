#!/usr/bin/env python3
"""Generate exact cut-cell alpha.air for the Hysing case-2 bubble.

Bubble: circle radius 0.25 centred at (0.5, 0.5) in a unit-width domain,
domain height 2, uniform Cartesian mesh nx x ny x 1 (dz = 0.1).

alpha.air = (area of cell inside the circle) / (cell area), computed by
Gauss-Legendre quadrature of the chord width, with sub-interval splitting at
all tangency points so the integrand is smooth on each sub-interval.

Cell labelling (blockMesh hex): label = i + j*nx, x fastest.

Usage: gen_alpha.py <nx> <ny> > 0/alpha.air
"""
import sys
import math
import numpy as np


def chord_width(y, xc, yc, r, x0, x1):
    """Width in x of the circle chord at height y, clipped to [x0, x1]."""
    dy = y - yc
    s2 = r * r - dy * dy
    if s2 <= 0.0:
        return 0.0
    s = math.sqrt(s2)
    lo = max(x0, xc - s)
    hi = min(x1, xc + s)
    return hi - lo if hi > lo else 0.0


def cell_overlap_area(x0, x1, y0, y1, xc, yc, r):
    """Exact-ish area of intersection of disk with rectangle."""
    # y-breakpoints where the chord geometry changes
    cands = [y0, y1, yc - r, yc + r]
    for xb in (x0, x1):
        dx = xb - xc
        if abs(dx) < r:
            for sgn in (-1, 1):
                yy = yc + sgn * math.sqrt(r * r - dx * dx)
                cands.append(yy)
    xs = sorted(set(cands))
    area = 0.0
    nodes, weights = np.polynomial.legendre.leggauss(40)
    for a, b in zip(xs[:-1], xs[1:]):
        if b <= a:
            continue
        lo, hi = max(a, y0), min(b, y1)
        if hi <= lo:
            continue
        mid = 0.5 * (lo + hi)
        half = 0.5 * (hi - lo)
        s = 0.0
        for w, t in zip(weights, nodes):
            s += w * chord_width(mid + half * t, xc, yc, r, x0, x1)
        area += half * s
    return area


def main():
    nx, ny = int(sys.argv[1]), int(sys.argv[2])
    w, hgt = 1.0, 2.0
    dx, dy = w / nx, hgt / ny
    xc, yc, r = 0.5, 0.5, 0.25

    alphas = []
    for j in range(ny):
        y0, y1 = j * dy, (j + 1) * dy
        for i in range(nx):
            x0, x1 = i * dx, (i + 1) * dx
            a = cell_overlap_area(x0, x1, y0, y1, xc, yc, r)
            alphas.append(min(a / (dx * dy), 1.0))

    total = sum(alphas) * dx * dy * 0.1
    exact = math.pi * r * r * 0.1
    print(f"// bubble volume  = {total:.10f}", file=sys.stderr)
    print(f"// exact (pi r^2) = {exact:.10f}", file=sys.stderr)
    print(f"// rel. error     = {abs(total - exact) / exact:.3e}", file=sys.stderr)

    out = sys.stdout
    out.write(
        "/*--------------------------------*- C++ -*----------------------------------*\\\n"
        "|  Generated by gen_alpha.py: exact cut-cell circle (r=0.25 at (0.5,0.5))  |\n"
        "\\*--------------------------------------------------------------------------*/\n"
        "FoamFile\n{\n    format      ascii;\n    class       volScalarField;\n"
        "    location    \"0\";\n    object      alpha.air;\n}\n"
        "// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //\n\n"
        "dimensions      [0 0 0 0 0 0 0];\n\n"
        f"internalField   nonuniform List<scalar> {len(alphas)}\n(\n"
    )
    for a in alphas:
        out.write(f"{a:.10f}\n")
    out.write(")\n;\n\nboundaryField\n{\n")
    for patch in ("bottom", "top", "walls"):
        out.write(f"    {patch}\n    {{\n        type            zeroGradient;\n    }}\n")
    out.write(
        "    defaultFaces\n    {\n        type            empty;\n    }\n}\n\n"
        "// ************************************************************************* //\n"
    )


if __name__ == "__main__":
    main()
